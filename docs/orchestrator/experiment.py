"""Experiment tracking for autoresearch-style prompt optimization.

Each wave 1 run is an experiment. The audit_score is a composite metric
computed from existing synthesis and metrics data. Higher is better.

Modeled after karpathy/autoresearch: fixed-budget experiments, single
metric, keep/discard selection pressure, persistent TSV log.
"""

import csv
import json
import subprocess
from dataclasses import dataclass
from pathlib import Path

from .config import ARTIFACTS_DIR, RESULTS_DIR


@dataclass
class ExperimentResult:
    """One row in experiments.tsv."""
    run_id: str
    commit: str          # git short hash at time of run
    audit_score: float   # composite metric (higher = better)
    regression: str      # "2/4" format
    findings: int        # confirmed findings count
    tool_pct: int        # % mandatory tools actually run (0-100)
    vectors: int         # total ruled-out vectors
    forge_tests: int     # hypotheses with Forge test evidence
    wall_time_s: int     # wall clock seconds
    status: str          # "keep" | "discard" | "crash"
    description: str     # what changed in this experiment


# --- Scoring ---

# Weights encode priorities: real findings > regression > tools > thoroughness
SCORE_WEIGHTS = {
    "regression":  25.0,   # 0-4 known bugs → 0-100 (25 pts each)
    "findings":    40.0,   # each confirmed finding = 40 pts (capped at 200)
    "tool_pct":     0.15,  # tool compliance % → 0-15 pts
    "vectors":      0.10,  # vectors/100 → 0-10 pts (capped)
    "forge_tests":  0.10,  # forge_test_pct → 0-10 pts (capped)
}


def compute_audit_score(wave_number: int = 1) -> ExperimentResult:
    """Compute audit_score from existing synthesis + metrics files.

    Reads:
      - wave{N}-synthesis.json (findings, ruled_out, tool warnings, regression)
      - wave{N}-metrics.json (turns, duration, agent count)
      - manifest.json (run_id)

    All these files are already generated by synthesizer.py and run_audit.py.
    This function does NOT run any agents — it scores what already exists.
    """
    synthesis_path = ARTIFACTS_DIR / f"wave{wave_number}-synthesis.json"
    metrics_path = RESULTS_DIR / f"wave{wave_number}-metrics.json"
    manifest_path = ARTIFACTS_DIR / "manifest.json"

    if not synthesis_path.exists():
        raise FileNotFoundError(f"No synthesis found: {synthesis_path}")

    synthesis = json.loads(synthesis_path.read_text())
    metrics = json.loads(metrics_path.read_text()) if metrics_path.exists() else {}
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}

    # --- Extract raw values ---

    # Findings
    confirmed_findings = len(synthesis.get("findings", []))

    # Regression
    regression_found, regression_total = _check_regression(wave_number)

    # Tool compliance (count agents that ran mandatory tools vs total)
    tool_warnings = synthesis.get("tool_coverage_warnings", [])
    agent_count = metrics.get("config", {}).get("agents", 6)
    tool_pct = _compute_tool_compliance(tool_warnings, agent_count)

    # Vectors ruled out
    vectors_ruled_out = synthesis.get("ruled_out_count", 0)

    # Forge test rate (count ruled-out vectors with test_file != null/N/A)
    forge_tests = _count_forge_tests(wave_number)

    # Wall time
    agents_data = metrics.get("agents", [])
    wall_time_s = max((a.get("duration_ms", 0) for a in agents_data), default=0) // 1000

    # --- Compute composite score ---
    score = 0.0
    score += regression_found * SCORE_WEIGHTS["regression"]
    score += min(confirmed_findings * SCORE_WEIGHTS["findings"], 200)
    score += tool_pct * SCORE_WEIGHTS["tool_pct"]
    score += min(vectors_ruled_out * SCORE_WEIGHTS["vectors"], 10)
    score += min(forge_tests * SCORE_WEIGHTS["forge_tests"], 10)

    # Git commit
    commit = _git_short_hash()

    return ExperimentResult(
        run_id=manifest.get("run_id", "unknown"),
        commit=commit,
        audit_score=round(score, 1),
        regression=f"{regression_found}/{regression_total}",
        findings=confirmed_findings,
        tool_pct=tool_pct,
        vectors=vectors_ruled_out,
        forge_tests=forge_tests,
        wall_time_s=wall_time_s,
        status="pending",  # caller sets to keep/discard
        description="",    # caller sets
    )


def _check_regression(wave_number: int) -> tuple[int, int]:
    """Re-run regression check against cumulative sidecars."""
    from .regression import check_regression
    from .run_audit import _collect_cumulative_sidecars
    cases_path = Path(__file__).parent / "regression_cases.json"
    if not cases_path.exists():
        return 0, 0
    sidecars = _collect_cumulative_sidecars(wave_number)
    result = check_regression(sidecars, cases_path)
    return len(result.get("found", [])), result.get("total", 4)


def _compute_tool_compliance(warnings: list[str], agent_count: int) -> int:
    """Compute tool compliance percentage from tool coverage warnings.

    4 mandatory tools per agent (audit_context_building, entry_point_analyzer,
    slither, aderyn). Each missing tool = one warning containing "did NOT run".
    """
    mandatory_per_agent = 4
    total_mandatory = mandatory_per_agent * agent_count
    missing = sum(1 for w in warnings if "did NOT run" in w)
    if total_mandatory == 0:
        return 100
    ran = total_mandatory - missing
    return max(0, min(100, int(100 * ran / total_mandatory)))


def _count_forge_tests(wave_number: int) -> int:
    """Count ruled-out vectors that have Forge test evidence."""
    from .synthesizer import collect_json_sidecars
    from .config import WAVES
    wave = WAVES[wave_number - 1]
    sidecars = collect_json_sidecars(wave)
    count = 0
    for sc in sidecars:
        for ro in sc.get("ruled_out_vectors", []):
            test_file = ro.get("test_file", "")
            if test_file and test_file not in ("null", "N/A", "None", ""):
                count += 1
    return count


def _git_short_hash() -> str:
    """Get current git short hash."""
    try:
        result = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            capture_output=True, text=True, timeout=5,
        )
        return result.stdout.strip() or "unknown"
    except Exception:
        return "unknown"


# --- TSV Logger ---

EXPERIMENTS_TSV = Path(__file__).parent.parent / "targets" / "full-system" / "experiments.tsv"
TSV_HEADER = "run_id\tcommit\taudit_score\tregression\tfindings\ttool_pct\tvectors\tforge_tests\twall_time_s\tstatus\tdescription\n"


def log_experiment(result: ExperimentResult) -> None:
    """Append an experiment result to experiments.tsv."""
    if not EXPERIMENTS_TSV.exists():
        EXPERIMENTS_TSV.write_text(TSV_HEADER)

    row = (
        f"{result.run_id}\t{result.commit}\t{result.audit_score}\t"
        f"{result.regression}\t{result.findings}\t{result.tool_pct}\t"
        f"{result.vectors}\t{result.forge_tests}\t{result.wall_time_s}\t"
        f"{result.status}\t{result.description}\n"
    )
    with open(EXPERIMENTS_TSV, "a") as f:
        f.write(row)

    print(f"  Experiment logged: audit_score={result.audit_score} "
          f"regression={result.regression} tools={result.tool_pct}% "
          f"vectors={result.vectors} status={result.status}")


def read_experiments() -> list[ExperimentResult]:
    """Read all experiments from TSV."""
    if not EXPERIMENTS_TSV.exists():
        return []
    results = []
    with open(EXPERIMENTS_TSV) as f:
        reader = csv.DictReader(f, delimiter="\t")
        for row in reader:
            results.append(ExperimentResult(
                run_id=row["run_id"],
                commit=row["commit"],
                audit_score=float(row["audit_score"]),
                regression=row["regression"],
                findings=int(row["findings"]),
                tool_pct=int(row["tool_pct"]),
                vectors=int(row["vectors"]),
                forge_tests=int(row.get("forge_tests", "0")),
                wall_time_s=int(row.get("wall_time_s", "0")),
                status=row["status"],
                description=row["description"],
            ))
    return results


def best_score() -> float:
    """Return the best audit_score from all experiments."""
    experiments = read_experiments()
    if not experiments:
        return 0.0
    return max(e.audit_score for e in experiments)
